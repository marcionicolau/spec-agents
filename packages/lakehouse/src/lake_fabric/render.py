DAG = '''

@dag(
    dag_id=CONFIG["dag_id"],
    schedule=CONFIG["schedule"],
    start_date=datetime.fromisoformat(CONFIG["start_date"]).replace(tzinfo=timezone.utc),
    catchup=CONFIG["catchup"],
    default_args={"retries": CONFIG["retries"]},
    max_active_runs=1,
    tags=CONFIG["tags"],
)
def medallion_ingest():
    @task
    def ensure_tables() -> bool:
        for statement in CONFIG["sql"]["ddl"]:
            _run(statement)
        return True

    @task
    def load_bronze(ready: bool) -> str:
        # The batch id is derived from the DAG run, so a retry of the same run replaces its own rows instead of duplicating them.
        run_id = get_current_context()["run_id"]
        batch_id = hashlib.sha1(f"{CONFIG['dag_id']}:{run_id}".encode()).hexdigest()[:32]
        _run(CONFIG["sql"]["bronze_reset"], [batch_id])
        ingested_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")
        columns = CONFIG["columns"]
        watermark = _watermark()
        records = _only_new(_read_records(watermark), watermark)
        rows = [[_normalise(rec.get(c["source_name"]), c["type"]) for c in columns] + [batch_id, CONFIG["source_label"], ingested_at]
                for rec in records]
        marks = "(" + ", ".join(["?"] * (len(columns) + 3)) + ")"
        for start in range(0, len(rows), CHUNK_ROWS):
            chunk = rows[start:start + CHUNK_ROWS]
            _run(CONFIG["sql"]["bronze_insert"] + ", ".join([marks] * len(chunk)), [v for row in chunk for v in row])
        log.info("bronze: %s rows landed in batch %s", len(rows), batch_id)
        return batch_id

    @task
    def quality_gate(batch_id: str) -> str:
        if _scalar(CONFIG["sql"]["bronze_count"], [batch_id]) == 0:
            if CONFIG["watermark"]:
                log.info("no new rows since the last watermark")
                return batch_id
            raise AirflowFailException("the source produced no rows")
        for key, sql in CONFIG["sql"]["bronze_null_keys"].items():
            nulls = _scalar(sql, [batch_id])
            if nulls:
                raise AirflowFailException(f"{nulls} row(s) with a null business key {key!r}")
        return batch_id

    @task
    def bronze_to_silver(batch_id: str) -> str:
        for statement in CONFIG["sql"]["silver_load"]:
            _run(statement, [batch_id] if "?" in statement else None)
        return batch_id

    @task
    def refresh_gold(batch_id: str) -> None:
        _run(CONFIG["sql"]["gold_refresh"])

    refresh_gold(bronze_to_silver(quality_gate(load_bronze(ensure_tables()))))


medallion_ingest()
'''

THIRD_PARTY = {"xlsx": "\nfrom openpyxl import load_workbook\n", "api": "\nimport requests\n", "mcp": "\nimport requests\n"}
STDLIB_EXTRA = {"api": "from urllib.parse import urlparse\n"}
TASKS = ("ensure_tables", "load_bronze", "quality_gate", "bronze_to_silver", "refresh_gold")


def render_dag(config: dict[str, Any]) -> str:
    kind = config["source"]["type"]
    needs_hook = kind in ("api", "mcp")
    text = HEAD.format(
        dag_id=config["dag_id"], source_type=kind, csv_import="import csv\n" if kind == "csv" else "", stdlib_extra=STDLIB_EXTRA.get(kind, ""), third_party=THIRD_PARTY.get(kind, ""),
        sdk_names="BaseHook, dag, get_current_context, task" if needs_hook else "dag, get_current_context, task",
        airflow2_extra="    from airflow.hooks.base import BaseHook\n" if needs_hook else "",
        config=pprint.pformat(config, width=110, sort_dicts=False))
    return "\n".join(line.rstrip() for line in (text + COMMON + READERS[kind] + DAG).splitlines()) + "\n"
