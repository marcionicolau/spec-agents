COMMON = '''

def _normalise(value, kind):
    """Landing format for bronze (VARCHAR): ISO date/timestamp in UTC, lower-case booleans, JSON for nested values."""
    if value is None or (isinstance(value, str) and value.strip() == ""):
        return None
    if isinstance(value, (dict, list)):
        return json.dumps(value, ensure_ascii=False)
    if kind in ("date", "timestamp"):
        text = value.isoformat() if hasattr(value, "isoformat") else str(value).strip()
        try:
            moment = datetime.fromisoformat(text.replace("Z", "+00:00"))
        except ValueError:
            return str(value)
        if moment.tzinfo is not None:
            moment = moment.astimezone(timezone.utc).replace(tzinfo=None)
        return moment.strftime("%Y-%m-%d") if kind == "date" else moment.strftime("%Y-%m-%d %H:%M:%S.%f")
    if kind == "boolean":
        return str(value).strip().lower()
    return str(value)


def _select(data, records_path):
    for key in filter(None, (records_path or "").split(".")):
        data = data[key]
    if isinstance(data, dict):
        data = [data]
    if not isinstance(data, list):
        raise AirflowFailException(f"records_path {records_path!r} does not point to a list of records")
    return data


def _dig(data, path):
    for key in path.split("."):
        if not isinstance(data, dict):
            return None
        data = data.get(key)
    return data


def _comparable(value, kind):
    """Value in a form that can be compared with the watermark (numbers as numbers, dates as ISO strings)."""
    if value is None:
        return None
    if kind in ("bigint", "double"):
        try:
            return float(value)
        except (TypeError, ValueError):
            return None
    return _normalise(value, kind)


def _watermark():
    """Highest watermark already in silver (None on the first run or when the load is not incremental)."""
    mark = CONFIG["watermark"]
    if not mark:
        return None
    value = _scalar(mark["sql"])
    return None if value is None else _normalise(value, mark["type"])


def _only_new(records, watermark):
    """Keep records at or after the watermark (>= so rows sharing the boundary value are never lost; merge de-duplicates)."""
    mark = CONFIG["watermark"]
    if not mark or watermark is None:
        return records
    limit = _comparable(watermark, mark["type"])
    kept = [r for r in records if (v := _comparable(r.get(mark["source_name"]), mark["type"])) is not None and v >= limit]
    log.info("incremental: %s of %s records at or after %s", len(kept), len(records), watermark)
    return kept


def _run(sql, parameters=None):
    return TrinoHook(trino_conn_id=CONFIG["trino_conn_id"]).run(sql, parameters=parameters)


def _scalar(sql, parameters=None):
    return TrinoHook(trino_conn_id=CONFIG["trino_conn_id"]).get_records(sql, parameters=parameters)[0][0]
'''

