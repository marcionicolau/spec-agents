def _headers():
    src = CONFIG["source"]
    headers = {"Accept": "application/json"}
    if src["auth_conn_id"]:
        headers["Authorization"] = f"Bearer {BaseHook.get_connection(src['auth_conn_id']).password}"
    return headers


def _read_records(watermark=None):
    """Call one tool of an MCP server over HTTP (JSON-RPC ``tools/call``) and take its JSON payload as records."""
    src = CONFIG["source"]
    payload = {"jsonrpc": "2.0", "id": 1, "method": "tools/call",
               "params": {"name": src["tool"], "arguments": src["arguments"]}}
    response = requests.post(src["url"], json=payload, headers=_headers(), timeout=src["timeout"])
    response.raise_for_status()
    body = response.json()
    if "error" in body:
        raise AirflowFailException(f"MCP error: {body['error']}")
    result = body["result"]
    if result.get("isError"):
        raise AirflowFailException(f"MCP tool {src['tool']!r} reported an error")
    content = result.get("structuredContent")
    if content is None:
        content = json.loads(next(c["text"] for c in result["content"] if c.get("type") == "text"))
    return _select(content, src["records_path"])
